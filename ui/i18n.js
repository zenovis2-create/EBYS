export const dictionaries = { ko, en };

export function t(key, params) {
  const s = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}

/** Pick the current language from a {ko,en} object (or return a plain string unchanged). */
export function pick(obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[lang] ?? obj.en ?? obj.ko ?? '';
}
